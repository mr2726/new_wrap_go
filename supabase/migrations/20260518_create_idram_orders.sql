create table if not exists public.idram_orders (
    id bigint generated by default as identity primary key,
    order_id text not null unique,
    user_id uuid not null references auth.users(id) on delete cascade,
    amount numeric(12, 2) not null check (amount > 0),
    status text not null default 'created',
    payment_method text not null default 'idram',
    description text,
    transaction_id text,
    raw_payload jsonb not null default '{}'::jsonb,
    prechecked_at timestamptz,
    paid_at timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idram_orders_user_id_idx on public.idram_orders (user_id);
create index if not exists idram_orders_status_idx on public.idram_orders (status);

alter table public.idram_orders enable row level security;

drop policy if exists "Users can read their Idram orders" on public.idram_orders;

create policy "Users can read their Idram orders"
on public.idram_orders
for select
using (auth.uid() = user_id);
